// 관계, 논리 연산자 
public class CompareOperator {

	public static void main(String[] args) {
		// 관계 연산자 
		System.out.println((3 == 4));
		System.out.println(3 != 4);
		System.out.println(3 > 4);
		System.out.println(3 < 4);
		System.out.println();
		
		// 논리 연산자(AND, OR, NOT)
		System.out.println((3 == 3 && 4 == 7));
		System.out.println(3 == 3 || 4 == 7);
		
	}

}
